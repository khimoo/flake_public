static int hhkb_audio_matches(const unsigned char *data, unsigned int size)
{
    if (size != 315)
        return 0;
    for (unsigned int i = 0; i < sizeof(hhkb_consumer_original); i++)
        if (data[66 + i] != hhkb_consumer_original[i])
            return 0;
    return 1;
}

static int hhkb_audio_patch(unsigned char *data, unsigned int size)
{
    if (!hhkb_audio_matches(data, size))
        return 0;
    for (unsigned int i = 0; i < 124; i++)
        data[66 + sizeof(hhkb_consumer_audio) + i] = data[191 + i];
    for (unsigned int i = 0; i < sizeof(hhkb_consumer_audio); i++)
        data[66 + i] = hhkb_consumer_audio[i];
    return 66 + sizeof(hhkb_consumer_audio) + 124;
}

